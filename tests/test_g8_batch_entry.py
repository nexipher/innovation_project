"""
The g8 batch entry (`scripts/g8_generate_batch.py`, stage 4.5).

The legacy generator is a G4-era multi-policy matrix (old toolbox, Qwen2.5,
applicability gating); running the g8 batch through it would mean the pipeline
the reviewer opens is not the pipeline that produced the data.  This entry
exists so the batch is generated by `main.build_pipeline` — the same
construction the acceptance run and the smoke use.

Pinned here, each because it would be a silent failure:

* a dry run **must not** write into the batch directory (mock sessions look
  exactly like real ones in a record — the converter cannot tell them apart);
* a real run refuses without the GPU authorization;
* the record carries the fields the converter reads (`evidence_check`,
  `verdict_status`, `trace_path`, the counters), because a missing one does not
  error — it silently drops a section of the sample.
"""

import json
import os
import subprocess
import sys

import pytest

from config import PROJECT_ROOT

pytestmark = pytest.mark.core

IMAGE = "dataset/GenImage_Test/Midjourney/0_midjourney_169.png"


def _manifest(tmp_path):
    """
    两张变体清单。路径是**相对仓库根**的（与 `build_variants_g4.py` 写出的清单
    同一约定：入口按 `PROJECT_ROOT + path` 打开图像），所以这里直接用仓库里的
    数据集图像；本测试验证的是入口，不是变体编码本身。
    """
    variants = {}
    for index, (treatment, container, quality) in enumerate(
            (("png", "png", None), ("jpeg_q70", "jpg", 70))):
        variants[f"{IMAGE}#{index}"] = {
            "variant_id": f"MJ_1_{treatment}",
            "source_id": "Midjourney/1", "label": "Fake", "generator": "Midjourney",
            "split": "train", "resolution": [1024, 1024], "treatment": treatment,
            "container": container, "quality": quality,
            "path": IMAGE,                       # 清单键是标识，`path` 才是文件
        }
    path = tmp_path / "manifest.json"
    path.write_text(json.dumps({"variants": variants}, ensure_ascii=False),
                    encoding="utf-8")
    return str(path)


@pytest.fixture(scope="module")
def dry_run(tmp_path_factory):
    """One mock session through the real entry, records redirected to a temp dir."""
    from scripts.g8_generate_batch import run_batch

    work = tmp_path_factory.mktemp("g8_batch_entry")
    manifest = _manifest(work)
    out = work / "records"
    metadata = run_batch("g8", "b_entry_test", manifest, "g8_default", 1, True,
                         False, True, "non-thinking", False, out_dir=str(out))
    records = [json.load(open(os.path.join(str(out), name), encoding="utf-8"))
               for name in os.listdir(str(out)) if name.endswith("__g8_default.json")]
    return {"metadata": metadata, "records": records, "out": str(out)}


class TestTheRecordCarriesWhatTheConverterReads:
    def test_the_schema_and_the_ledger_verdict_are_there(self, dry_run):
        record = dry_run["records"][0]
        assert record["record_schema"]
        assert record["evidence_check"], "缺 evidence_check 会被转换门禁判成旧 schema"
        assert record["verdict_status"] in ("model_concluded", "no_parseable_conclusion")

    def test_the_trace_is_written_and_pointed_at(self, dry_run):
        record = dry_run["records"][0]
        assert record["trace_path"]
        path = os.path.join(PROJECT_ROOT, record["trace_path"])
        assert os.path.exists(path)
        trace = json.load(open(path, encoding="utf-8"))
        assert trace["conversations"], "trace 里没有对话"

    def test_the_counters_keep_their_record_names(self, dry_run):
        counters = dry_run["records"][0]["counters"]
        assert counters["expert_calls"] >= 1
        assert counters["model_turns"] >= 1
        assert counters["weighted_cost"] is not None

    def test_the_delivery_shape_is_stamped_on_the_tokens(self, dry_run):
        """批次数据必须自证"模型当时看到的是精简包"。"""
        tokens = dry_run["records"][0]["evidence"]
        assert tokens and all(t.get("model_delivered") == "slim" for t in tokens)


class TestTheDryRunStaysOutOfTheBatch:
    def test_it_writes_where_it_was_told(self, dry_run):
        assert os.path.isdir(dry_run["out"])
        assert "dry_run" in dry_run["out"] or "tmp" in dry_run["out"]

    def test_the_traces_of_a_dry_run_go_with_its_records(self, tmp_path):
        """
        记录隔离了、trace 没隔离，就等于把 mock 会话留在批次目录里给审阅者翻。
        真实发生过一次（6 个干跑 trace 落进了 b1 的 trace 目录）。
        """
        from scripts.g8_generate_batch import run_batch

        manifest = _manifest(tmp_path)
        out = tmp_path / "records"
        run_batch("g8", "b_entry_test2", manifest, "g8_default", 1, True, False,
                  True, "non-thinking", False, out_dir=str(out))
        assert os.path.isdir(os.path.join(str(out), "sessions"))
        assert any(name.endswith(".json")
                   for name in os.listdir(os.path.join(str(out), "sessions")))

    def test_no_record_lands_in_the_batch_directory(self, tmp_path):
        """默认干跑目录是 traces/dry_run_records/…，批次目录一个文件都不加。"""
        from utils.batch import batch_paths

        records = [name for name in os.listdir(batch_paths("b1", "g8")["trajectories"])
                   if name.endswith(".json")]
        # b1 是真实批次：里面只该有真实会话（或为空，比如测试机上没跑过）。
        for name in records:
            assert "dry_run" not in name


class TestTheInputsAreTheSameAsTheReferenceBatch:
    """
    b2 与 b1 的对照成立，前提是**输入文件逐字节相同**。"同一个 seed 重建"只是
    假定编码器确定性——名字、来源都一样而字节不同，记录里看不出来，对照就废了。
    这里钉住：按真实文件 sha256 比对，任何不同即拒绝启动。

    **夹具全部落在 tmp_path**：这组测试曾经用 `batch_paths()` 拼路径，跑一次就在
    `sft_data/g8/variants/` 下留了两个目录（工作区因此变脏）。现在入口接收显式
    路径，测试不碰仓库；末尾还断言"用的确实是临时目录"。
    """

    def _pair(self, tmp_path, same: bool):
        source_dir = tmp_path / "ref"
        target_dir = tmp_path / "new"
        source_dir.mkdir()
        target_dir.mkdir()
        (source_dir / "v.png").write_bytes(b"AAA")
        (target_dir / "v.png").write_bytes(b"AAA" if same else b"BBB")
        entry = {"variant_id": "v", "source_id": "s", "label": "Fake",
                 "generator": "g", "split": "train", "resolution": [8, 8],
                 "treatment": "png", "container": "png", "quality": None}
        source_manifest = source_dir / "manifest.json"
        source_manifest.write_text(json.dumps({"variants": {
            str(source_dir / "v.png"): entry}}), encoding="utf-8")
        target_manifest = target_dir / "manifest.json"
        target_manifest.write_text(json.dumps({"variants": {
            str(target_dir / "v.png"): entry}}), encoding="utf-8")
        # 防回归：夹具必须在临时目录里
        assert str(tmp_path) in str(target_manifest) and str(tmp_path) in str(source_manifest)
        return str(target_manifest), str(source_manifest)

    def test_identical_inputs_pass(self, tmp_path):
        from scripts.g8_generate_batch import assert_variants_identical

        manifest, source = self._pair(tmp_path, same=True)
        assert_variants_identical(manifest, source)      # 不抛 = 通过

    def test_byte_differences_refuse_to_start(self, tmp_path):
        from scripts.g8_generate_batch import assert_variants_identical

        manifest, source = self._pair(tmp_path, same=False)
        with pytest.raises(SystemExit) as caught:
            assert_variants_identical(manifest, source)
        assert "字节不同" in str(caught.value)


class TestTheGates:
    def test_a_real_run_refuses_without_authorization(self, tmp_path):
        manifest = _manifest(tmp_path)
        env = {k: v for k, v in os.environ.items() if k != "FORENSIC_ALLOW_GPU"}
        result = subprocess.run(
            [sys.executable, "scripts/g8_generate_batch.py", "--generation", "g8",
             "--batch", "b_entry_test", "--manifest", manifest, "--limit", "1"],
            cwd=PROJECT_ROOT, capture_output=True, text=True, timeout=300, env=env)
        assert result.returncode == 2
        assert "FORENSIC_ALLOW_GPU" in result.stdout + result.stderr

    def test_a_missing_manifest_says_how_to_build_one(self, tmp_path):
        result = subprocess.run(
            [sys.executable, "scripts/g8_generate_batch.py", "--generation", "g8",
             "--batch", "b_entry_test", "--manifest", str(tmp_path / "nope.json"),
             "--dry-run"],
            cwd=PROJECT_ROOT, capture_output=True, text=True, timeout=300)
        assert result.returncode == 2
        assert "build_variants_g4.py" in result.stdout + result.stderr


